// platform_win32.hpp: the few Windows-specific services the app needs.
#pragma once

#include <cstdint>
#include <filesystem>
#include <optional>
#include <string>
#include <string_view>

struct GLFWwindow;

namespace pfl {

// Writes a line to stderr (visible in Debug's console) and to the debugger output window.
void logMessage(std::string_view message);

// Logs the message and shows it in a modal Windows MessageBox (works without a console).
void showFatalError(std::string_view title, std::string_view message);

// Same message box for recoverable errors (e.g. a file that could not be read).
void showErrorMessage(GLFWwindow* owner, std::string_view title, std::string_view message);

// PotentialFlowLab.exe [scene.json] [--export-image out.png] [--export-field out.csv]
//                     [--export-lines out.csv] [--export-surface out.csv]
//                     [--export-video out.mp4|out.gif [--video-seconds 6] [--video-fps 30]]
// A scene file alone (e.g. dropped on the exe) is opened. With an export option the app renders
// the scene, writes the files and quits, so report figures and data can be regenerated by script.
// A video is a GIF when its name ends in .gif, an MP4 otherwise; it is recorded after the other
// exports, from the same state.
struct CommandLine {
    std::optional<std::filesystem::path> scene;
    std::optional<std::filesystem::path> exportImage;
    std::optional<std::filesystem::path> exportField;
    std::optional<std::filesystem::path> exportLines;
    std::optional<std::filesystem::path> exportSurface;
    std::optional<std::filesystem::path> exportVideo;
    std::optional<double> videoSeconds;
    std::optional<int> videoFps;
    std::string error; // unknown option or missing or invalid value

    bool batch() const { return exportImage || exportField || exportLines || exportSurface || exportVideo; }
};
CommandLine parseCommandLine();

// Native Open / Save As dialogs for scene files (*.json). Empty if the user cancels.
std::optional<std::filesystem::path> showOpenSceneDialog(GLFWwindow* owner);
std::optional<std::filesystem::path> showSaveSceneDialog(GLFWwindow* owner, const std::filesystem::path& suggested);

// Save As dialogs for exports.
std::optional<std::filesystem::path> showSavePngDialog(GLFWwindow* owner, const std::filesystem::path& suggested);
std::optional<std::filesystem::path> showSaveCsvDialog(GLFWwindow* owner, const std::filesystem::path& suggested);
std::optional<std::filesystem::path> showSaveVideoDialog(GLFWwindow* owner, const std::filesystem::path& suggested, bool gif);

// Writes 8-bit RGBA pixels (rows top to bottom) as a PNG with the Windows Imaging Component.
// The alpha channel is dropped. On failure returns false and sets `error`.
bool writePng(const std::filesystem::path& path, int width, int height, const std::uint8_t* rgba, std::string& error);

} // namespace pfl
